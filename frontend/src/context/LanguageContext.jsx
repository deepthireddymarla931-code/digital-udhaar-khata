const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [currentLang, setCurrentLang] = useState(() => {
    return localStorage.getItem('app_language') || 'en';
  });

  const setLanguage = (langKey) => {
    if (translations[langKey]) {
      setCurrentLang(langKey);
      localStorage.setItem('app_language', langKey);
    }
  };

  const t = (key) => {
    const langObj = translations[currentLang] || translations.en;
    return langObj[key] || translations.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLang, setLanguage, t, availableLanguages: Object.keys(translations) }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
